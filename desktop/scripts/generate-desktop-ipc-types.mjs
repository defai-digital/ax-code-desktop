#!/usr/bin/env node
// Writes ui/src/lib/desktopIpcContract.gen.ts from the Electron IPC contract
// (ADR-019, SPEC-2026-10-19-desktop-ipc-contract-v2). The IPC contract check
// fails when the committed file differs from this output.
import { readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const desktopRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
export const contractPath = path.join(desktopRoot, "packages", "electron", "src", "desktop-ipc-contract.json")
export const generatedTypesPath = path.join(desktopRoot, "packages", "ui", "src", "lib", "desktopIpcContract.gen.ts")

const TS_TYPES = {
  string: "string",
  number: "number",
  integer: "number",
  boolean: "boolean",
  object: "Record<string, unknown>",
  array: "unknown[]",
  "string[]": "string[]",
}

const paramType = (schema) => {
  const base =
    schema.type === "string" && Array.isArray(schema.enum) && schema.enum.length > 0
      ? schema.enum.map((value) => JSON.stringify(value)).join(" | ")
      : TS_TYPES[schema.type]
  if (!base) throw new Error(`Unknown param type: ${schema.type}`)
  return schema.nullable ? `${base} | null` : base
}

const argsType = (entry) => {
  if (entry.args === "none") return "Record<string, never>"
  if (!entry.params) return "Record<string, unknown>"
  const fields = Object.entries(entry.params).map(
    ([name, schema]) => `    ${name}${schema.optional ? "?" : ""}: ${paramType(schema)}`,
  )
  return fields.length === 0 ? "Record<string, never>" : `{\n${fields.join("\n")}\n  }`
}

export const renderDesktopIpcTypes = (contract) => {
  const commands = [...(contract.commands ?? [])].sort((a, b) => a.command.localeCompare(b.command))
  const lines = [
    "// Generated by desktop/scripts/generate-desktop-ipc-types.mjs from",
    "// packages/electron/src/desktop-ipc-contract.json. Do not edit by hand.",
    "",
    "export type DesktopCommandArgs = {",
    ...commands.map((entry) => `  ${entry.command}: ${argsType(entry)}`),
    "}",
    "",
    "export type DesktopCommandName = keyof DesktopCommandArgs",
    "",
  ]
  return lines.join("\n")
}

export const readContract = () => JSON.parse(readFileSync(contractPath, "utf8"))

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(generatedTypesPath, renderDesktopIpcTypes(readContract()))
  console.log(`Wrote ${path.relative(desktopRoot, generatedTypesPath)}`)
}
